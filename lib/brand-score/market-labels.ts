// GT集計表の行・列ラベルの共通判定（I/O を持たない純関数）
// ============================================================
// 「その他」「あてはまるものはない」のような集計上の受け皿は、
// 選択肢としても競合他社としても中身が無い。
//
// market-extras（ランキング表示）と market-auto-map（競合の自動抽出）の
// 両方で同じ判定が要るが、market-extras は market-auto-map を import して
// いるため、逆向きに import すると循環する。共有するものはここに置く。
// ============================================================

/**
 * 集計表の「中身ではない」行・列。
 *
 * ⚠️ 「その他」だけは完全一致にしている。「その他の医療機器」のような
 *    実在の選択肢まで落とさないため。他は接頭辞一致で足りる
 *    （「無回答」「不明」等はそれ自体で受け皿を意味する）。
 *
 * 実データの例（2026年GT表 q1_AC）:
 *   その他 13.6% ／ あてはまるものはない 11.8%
 * どちらもコード付きの行として入っており、競合他社として扱うと
 * ベンチマークの最大値と順位の母数が狂う。
 */
export const NOISE_LABEL =
  /^(回答個数|あてはまるものはない|あてはまるものはひとつもない|その他$|不明|無回答)/

/** ラベルが集計上の受け皿か。空・未設定も中身が無いものとして扱う */
export function isNoiseLabel(label: string | null | undefined): boolean {
  if (!label) return true
  return NOISE_LABEL.test(label.trim())
}
